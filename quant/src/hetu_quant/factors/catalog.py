def _complete_definition(definition):
    aliases = (
        *definition.aliases,
        *_COMMON_ALIASES.get(definition.factor_id, ()),
        definition.factor_id.replace("_", " "),
    )
    return replace(definition, aliases=aliases, direction=_DIRECTIONS.get(definition.factor_id))


