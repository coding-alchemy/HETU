@dataclass(frozen=True)
class FactorDefinition:
    factor_id: str
    name: str
    category: str
    subject_kind: tuple[str, ...]
    compute: Callable
    defaults: dict
    example_id: str
    fields: dict[str, tuple[str, ...]]
    chapters: str
    unit: str
    aliases: tuple[str, ...] = ()
    direction: str | None = None
    version: str = "1"
    purpose: str = "factor_calculation"
    additional_presets: tuple[tuple[str, dict], ...] = ()

    @property
    def presets(self):
        return {
            "默认": dict(self.defaults),
            **{name: {**self.defaults, **params} for name, params in self.additional_presets},
        }

    @property
    def case_ids(self):
        return ("positive", "boundary", "local") if self.factor_id == "up_amount_share" else ("positive", "boundary")

    @property
    def effect_validation(self):
        return dict(
            status="not_evaluated",
            hypothesis=f"{self.name}能否描述同类对象未来的收益或风险差异？",
            subject_kind=self.subject_kind,
            comparison="相同可比对象的同期基准",
            horizon="未来一个月，另由研究协议事前定义",
            evidence_refs=[],
        )


